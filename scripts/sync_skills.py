"""Maintain portable Claude Code/Codex discovery mirrors from canonical skills/."""

import argparse
import shutil
from pathlib import Path


def synchronize(root: Path, check: bool) -> bool:
    source = root / "skills"
    files = {p.relative_to(source): p.read_bytes() for p in source.rglob("*") if p.is_file()}
    if not any(path.name == "SKILL.md" for path in files):
        raise ValueError("No canonical skills found; refusing empty discovery adapters.")
    valid = True
    for name in (".agents", ".claude"):
        target = root / name / "skills"
        if target.is_symlink():
            raise ValueError("Discovery target is a symlink; review before replacing it.")
        existing = {
            p.relative_to(target): p.read_bytes()
            for p in target.rglob("*")
            if p.is_file() and p.name != ".generated"
        }
        if existing != files:
            valid = False
            if not check:
                if target.exists():
                    if not (target / ".generated").exists():
                        raise ValueError(f"Refusing to overwrite unmanaged skills: {target}")
                    shutil.rmtree(target)
                target.mkdir(parents=True)
                for path, contents in files.items():
                    destination = target / path
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    destination.write_bytes(contents)
                (target / ".generated").write_text("Generated by scripts/sync_skills.py\n")
    return valid


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        valid = synchronize(args.root.resolve(), args.check)
    except ValueError as error:
        parser.exit(2, f"{error}\n")
    if args.check and not valid:
        parser.exit(1, "Discovery adapters missing or stale; run make agents-sync.\n")
